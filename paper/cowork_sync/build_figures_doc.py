"""Rebuild 'd1 Figures.docx': title page, numbered figures (one per page, boxed,
caption placeholder), then 'Pending regeneration' pages for legacy entries not yet
regenerated (plus reference images).

usage: build_figures_doc.py out.docx coverage.yaml legacy_dir fig_id=path.png [fig_id=path.png ...]
"""
import sys, yaml
from xml.sax.saxutils import escape
import docx
from docx.shared import Pt, Inches
from docx.enum.text import WD_BREAK
from docx.oxml import parse_xml
from docx.oxml.ns import qn, nsdecls
from PIL import Image
import frame_figures as ff


def caption(label, fig_id, placeholder=None):
    rb = '<w:rPr><w:b/><w:sz w:val="18"/><w:szCs w:val="18"/></w:rPr>'
    hl = '<w:rPr><w:i/><w:sz w:val="18"/><w:szCs w:val="18"/><w:highlight w:val="yellow"/></w:rPr>'
    gr = '<w:rPr><w:i/><w:color w:val="595959"/><w:sz w:val="18"/><w:szCs w:val="18"/></w:rPr>'
    body = (f'<w:r>{gr}<w:t xml:space="preserve">{escape(placeholder)}</w:t></w:r>' if placeholder
            else f'<w:r>{hl}<w:t xml:space="preserve">[Caption for {fig_id} — to be written]</w:t></w:r>')
    return parse_xml(f'<w:p {nsdecls("w")}><w:pPr><w:keepLines/><w:spacing w:before="120" w:after="0"/></w:pPr>'
                     f'<w:r>{rb}<w:t xml:space="preserve">{escape(label)}. </w:t></w:r>{body}</w:p>')

MAX_W_IN, MAX_H_IN = 6.3, 8.0


def fit_width(path, max_h=MAX_H_IN):
    w, h = Image.open(path).size
    return min(MAX_W_IN, max_h * w / h)


def main(out, cov_path, legacy_dir, figs):
    cov = yaml.safe_load(open(cov_path))["legacy"]
    pending = [e for e in cov if e["kind"] == "reference" or (e["kind"] == "figure" and not e.get("regenerated"))]
    d = docx.Document()
    s = d.sections[0]
    s.page_width, s.page_height = Inches(8.5), Inches(11)
    for m in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(s, m, Inches(1))

    def para(text, size, **kw):
        r = d.add_paragraph().add_run(text); r.font.size = Pt(size)
        for k, v in kw.items(): setattr(r, k, v)

    def pagebreak():
        d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    placed = []  # (descr, path)

    def add_img(path, descr, max_h=MAX_H_IN):
        p = d.add_paragraph(); p.add_run().add_picture(path, width=Inches(fit_width(path, max_h)))
        dp = p._p.find(".//" + qn("wp:docPr")); dp.set("descr", descr); dp.set("name", descr)
        placed.append((descr, path))

    para("Hippocampus computational modeling paper — Figures", 14, bold=True)
    para("Companion to the manuscript (d1). One figure per page, numbered to match the text. Figures are "
         "generated by the RatInABox paper/ pipeline and replaced here automatically; write captions in the "
         "highlighted lines, and don't edit the images.", 9, italic=True)
    if pending:
        para('The last section, "Pending regeneration", holds figures from the earlier draft that the pipeline '
             "hasn't rebuilt yet. Each page is removed once its replacement exists.", 9, italic=True)
    for fid, path in figs:
        pagebreak(); add_img(path, fid)
    if pending:
        pagebreak(); para("Pending regeneration", 12, bold=True)
        para("Earlier-draft figures, kept so nothing is lost. Not part of the numbered figures.", 9, italic=True)
        for i, e in enumerate(pending):
            if i: pagebreak()
            add_img(f"{legacy_dir}/{e['file']}", "legacy:" + e["file"], max_h=6.8)
    bycov = {"legacy:" + e["file"]: e for e in pending}

    num = 0
    for dr in list(d.element.body.iter(qn("w:drawing"))):
        fid = dr.find(".//" + qn("wp:docPr")).get("descr")
        p = dr
        while p.tag != qn("w:p"):
            p = p.getparent()
        box = ff.figure_box(fid); p.addprevious(box)
        cell = box.find(".//" + qn("w:tc")); cell.append(p)
        ppr = p.find(qn("w:pPr"))
        if ppr is None:
            ppr = parse_xml(f'<w:pPr {nsdecls("w")}/>'); p.insert(0, ppr)
        ppr.append(parse_xml(f'<w:jc {nsdecls("w")} w:val="center"/>'))
        ppr.append(parse_xml(f'<w:keepNext {nsdecls("w")}/>'))
        if fid.startswith("legacy:"):
            e = bycov[fid]
            if e["kind"] == "reference":
                label = f"Reference (source paper, not regenerated): {e.get('note', '').strip()}"
            else:
                label = f"Pending regeneration → {e['figure']}: {', '.join(e['panels'])}" + (f" — {e['note']}" if e.get("note") else "")
            rpr = '<w:rPr><w:color w:val="595959"/><w:sz w:val="18"/><w:szCs w:val="18"/></w:rPr>'
            cell.append(parse_xml(
                f'<w:p {nsdecls("w")}><w:pPr><w:spacing w:before="120" w:after="0"/></w:pPr>'
                f'<w:r>{rpr}<w:t xml:space="preserve">{escape(label)}</w:t></w:r><w:r><w:br/></w:r>'
                f'<w:r>{rpr}<w:t xml:space="preserve">{escape("paper/legacy/" + e["file"])}</w:t></w:r></w:p>'))
        else:
            num += 1
            cell.append(ff.caption_paragraph(num, fid))
    d.save(out)
    print("figures:", [f for f, _ in figs], "| pending:", [e["file"] for e in pending])


if __name__ == "__main__":
    out, cov, legacy_dir, *pairs = sys.argv[1:]
    main(out, cov, legacy_dir, [tuple(p.split("=", 1)) for p in pairs])
